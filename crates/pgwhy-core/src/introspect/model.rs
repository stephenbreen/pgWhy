#[cfg(test)]
mod tests {
    use super::*;

    fn idx(name: &str, cols: &[&str]) -> IndexInfo {
        IndexInfo {
            name: name.into(),
            definition: String::new(),
            method: "btree".into(),
            is_unique: true,
            is_primary: false,
            is_valid: true,
            predicate: None,
            columns: cols.iter().map(|c| c.to_string()).collect(),
            include_columns: vec![],
            has_expressions: false,
            key_columns_not_null: true,
            constraint: None,
            size_bytes: None,
        }
    }

    #[test]
    fn primary_key_wins() {
        let mut pk = idx("t_pkey", &["a", "b"]);
        pk.is_primary = true;
        pk.constraint = Some("t_pkey".into());
        let p = EditProvenance::derive(RelationKind::Table, &[idx("u", &["c"]), pk]);
        assert_eq!(
            p.key,
            Some(EditKey::PrimaryKey {
                constraint: Some("t_pkey".into()),
                columns: vec!["a".into(), "b".into()]
            })
        );
    }

    #[test]
    fn unusable_unique_indexes_are_skipped() {
        let mut partial = idx("partial", &["a"]);
        partial.predicate = Some("(a > 0)".into());
        let mut nullable = idx("nullable", &["b"]);
        nullable.key_columns_not_null = false;
        let mut expr = idx("expr", &["lower(c)"]);
        expr.has_expressions = true;
        let mut invalid = idx("invalid", &["d"]);
        invalid.is_valid = false;
        let mut non_unique = idx("plain", &["e"]);
        non_unique.is_unique = false;
        let all = [partial, nullable, expr, invalid, non_unique];
        let p = EditProvenance::derive(RelationKind::Table, &all);
        assert_eq!(p.key, None);
        assert!(p.read_only_reason.is_some());

        let mut with_good = all.to_vec();
        with_good.push(idx("wide", &["x", "y"]));
        with_good.push(idx("narrow", &["z"]));
        let p = EditProvenance::derive(RelationKind::PartitionedTable, &with_good);
        assert_eq!(p.key.unwrap().columns(), ["z".to_string()]);
    }

    #[test]
    fn non_tables_are_read_only() {
        for k in [
            RelationKind::View,
            RelationKind::MaterializedView,
            RelationKind::ForeignTable,
            RelationKind::Sequence,
        ] {
            let p = EditProvenance::derive(k, &[]);
            assert!(p.key.is_none() && p.read_only_reason.is_some(), "{k:?}");
        }
    }
}
