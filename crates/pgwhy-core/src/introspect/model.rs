//! The catalog model the UI (tree, details panel, completion) and the SQL generators
//! (Script-as, top-N, edit layer) are built against. All plain data, serde-serializable.
//!
//! Names are stored raw (exactly as in the catalog); anything that renders them into SQL must
//! go through [`super::quote`].

use serde::{Deserialize, Serialize};

/// A database on the server (`pg_database`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DatabaseInfo {
    pub name: String,
    pub owner: String,
    pub encoding: String,
    pub collate: String,
    pub ctype: String,
    /// `c` (libc), `i` (ICU) or `b` (builtin); `None` before PostgreSQL 15.
    pub locale_provider: Option<String>,
    pub allow_connections: bool,
    pub is_template: bool,
    pub comment: Option<String>,
}

/// A schema in one database (`pg_namespace`, minus toast and temp schemas).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SchemaInfo {
    pub name: String,
    pub owner: String,
    /// `pg_catalog` / `information_schema`: shown collapsed/dimmed, never auto-expanded.
    pub is_system: bool,
    pub comment: Option<String>,
}

/// `schema.name`, raw (unquoted).
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub struct QualifiedName {
    pub schema: String,
    pub name: String,
}

impl QualifiedName {
    pub fn new(schema: impl Into<String>, name: impl Into<String>) -> Self {
        Self {
            schema: schema.into(),
            name: name.into(),
        }
    }

    /// The quoted, SQL-ready form.
    pub fn to_sql(&self) -> String {
        super::quote::qualified(&self.schema, &self.name)
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RelationKind {
    Table,
    PartitionedTable,
    View,
    MaterializedView,
    ForeignTable,
    Sequence,
}

impl RelationKind {
    pub(crate) fn from_relkind(c: &str) -> Option<Self> {
        Some(match c {
            "r" => Self::Table,
            "p" => Self::PartitionedTable,
            "v" => Self::View,
            "m" => Self::MaterializedView,
            "f" => Self::ForeignTable,
            "S" => Self::Sequence,
            _ => return None,
        })
    }

    /// Plain or partitioned table.
    pub fn is_table(self) -> bool {
        matches!(self, Self::Table | Self::PartitionedTable)
    }

    /// Has a column list (everything but sequences).
    pub fn has_columns(self) -> bool {
        self != Self::Sequence
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Identity {
    /// `GENERATED ALWAYS AS IDENTITY`
    Always,
    /// `GENERATED BY DEFAULT AS IDENTITY`
    ByDefault,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Generated {
    Stored,
    /// PostgreSQL 18+.
    Virtual,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ColumnInfo {
    pub name: String,
    /// `attnum`: 1-based position among *all* columns ever defined (gaps after drops).
    pub ordinal: i16,
    /// `format_type(atttypid, atttypmod)`, e.g. `character varying(40)`, `numeric(10,2)`.
    pub data_type: String,
    /// The type oid, for binding parameters of the right type.
    pub type_oid: u32,
    pub not_null: bool,
    /// `pg_get_expr` of the default; `None` for generated columns (see `generation_expr`).
    pub default: Option<String>,
    pub identity: Option<Identity>,
    pub generated: Option<Generated>,
    pub generation_expr: Option<String>,
    pub comment: Option<String>,
}

impl ColumnInfo {
    /// Whether an INSERT/UPDATE may set this column (generated and identity-ALWAYS can't be
    /// written without OVERRIDING clauses).
    pub fn is_writable(&self) -> bool {
        self.generated.is_none() && self.identity != Some(Identity::Always)
    }
}

/// A table/view/matview/foreign table/sequence with its columns — what one schema expansion
/// returns per relation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RelationInfo {
    pub oid: u32,
    pub schema: String,
    pub name: String,
    pub kind: RelationKind,
    pub owner: String,
    pub comment: Option<String>,
    /// Ordered by ordinal; empty for sequences.
    pub columns: Vec<ColumnInfo>,
    /// Set on partitions: the partitioned parent.
    pub partition_of: Option<QualifiedName>,
    /// Set on partitions: e.g. `FOR VALUES FROM (1) TO (100)`.
    pub partition_bound: Option<String>,
    /// Set on partitioned tables: e.g. `RANGE (id)`.
    pub partition_key: Option<String>,
    /// Set on partitioned tables: direct children, sorted by schema then name.
    pub partitions: Vec<QualifiedName>,
}

impl RelationInfo {
    pub fn qualified_name(&self) -> QualifiedName {
        QualifiedName::new(&self.schema, &self.name)
    }

    pub fn column(&self, name: &str) -> Option<&ColumnInfo> {
        self.columns.iter().find(|c| c.name == name)
    }

    /// A partition (shown under its parent in the tree).
    pub fn is_partition(&self) -> bool {
        self.partition_of.is_some()
    }
}

/// Everything one schema expansion loads (one round trip): relations with their columns.
/// Functions are a separate lazy pull ([`FunctionInfo`]).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SchemaContents {
    pub schema: String,
    /// Sorted by name.
    pub relations: Vec<RelationInfo>,
}

impl SchemaContents {
    pub fn relation(&self, name: &str) -> Option<&RelationInfo> {
        self.relations.iter().find(|r| r.name == name)
    }
}

