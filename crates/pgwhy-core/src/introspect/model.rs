/// The key a grid edit addresses rows by.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum EditKey {
    PrimaryKey {
        constraint: Option<String>,
        columns: Vec<String>,
    },
    /// No PK: the narrowest unique, valid, non-partial, expression-free index whose columns
    /// are all NOT NULL.
    UniqueKey {
        index: String,
        constraint: Option<String>,
        columns: Vec<String>,
    },
}

impl EditKey {
    pub fn columns(&self) -> &[String] {
        match self {
            EditKey::PrimaryKey { columns, .. } | EditKey::UniqueKey { columns, .. } => columns,
        }
    }
}

/// Whether (and how) rows of a relation can be edited in the grid (plan R16 / EC-4).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct EditProvenance {
    pub key: Option<EditKey>,
    /// Why editing is disabled, when `key` is `None`.
    pub read_only_reason: Option<String>,
}

impl EditProvenance {
    /// Derive the edit key from a relation's kind and indexes.
    pub fn derive(kind: RelationKind, indexes: &[IndexInfo]) -> Self {
        let not_a_table = match kind {
            RelationKind::Table | RelationKind::PartitionedTable => None,
            RelationKind::View => Some("views are read-only in the grid"),
            RelationKind::MaterializedView => Some("materialized views cannot be edited"),
            RelationKind::ForeignTable => Some("foreign tables are read-only in the grid"),
            RelationKind::Sequence => Some("sequences cannot be edited"),
        };
        if let Some(reason) = not_a_table {
            return Self::read_only(reason);
        }
        if let Some(pk) = indexes.iter().find(|i| i.is_primary && i.is_valid) {
            return Self {
                key: Some(EditKey::PrimaryKey {
                    constraint: pk.constraint.clone(),
                    columns: pk.columns.clone(),
                }),
                read_only_reason: None,
            };
        }
        let best = indexes
            .iter()
            .filter(|i| i.is_edit_key_candidate())
            .min_by(|a, b| {
                a.columns
                    .len()
                    .cmp(&b.columns.len())
                    // prefer a declared constraint over a bare unique index, then by name
                    .then(b.constraint.is_some().cmp(&a.constraint.is_some()))
                    .then(a.name.cmp(&b.name))
            });
        match best {
            Some(i) => Self {
                key: Some(EditKey::UniqueKey {
                    index: i.name.clone(),
                    constraint: i.constraint.clone(),
                    columns: i.columns.clone(),
                }),
                read_only_reason: None,
            },
            None => {
                Self::read_only("the table has neither a primary key nor a unique NOT NULL key")
            }
        }
    }

    fn read_only(reason: &str) -> Self {
        Self {
            key: None,
            read_only_reason: Some(reason.to_string()),
        }
    }
}

/// Everything the details panel shows for one relation, fetched fresh on select/refresh.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct RelationDetails {
    /// Re-read with the details, so the panel is consistent with constraints/indexes.
    pub relation: RelationInfo,
    /// PK first, then FKs, unique, check, exclusion; by name within a kind.
    pub constraints: Vec<ConstraintInfo>,
    /// Primary first, then by name.
    pub indexes: Vec<IndexInfo>,
    pub stats: RelationStats,
    /// `pg_get_viewdef` for views and materialized views.
    pub view_definition: Option<String>,
    /// For views and foreign tables; tables are always fully updatable.
    pub updatability: Option<Updatability>,
    pub sequence: Option<SequenceInfo>,
    pub provenance: EditProvenance,
}

impl RelationDetails {
    pub fn primary_key(&self) -> Option<&ConstraintInfo> {
        self.constraints
            .iter()
            .find(|c| c.kind == ConstraintKind::PrimaryKey)
    }
}

/// What go-to-object can land on.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ObjectKind {
    Table,
    PartitionedTable,
    View,
    MaterializedView,
    ForeignTable,
    Sequence,
    Function,
    Procedure,
    Aggregate,
    Window,
}

impl From<RelationKind> for ObjectKind {
    fn from(k: RelationKind) -> Self {
        match k {
            RelationKind::Table => Self::Table,
            RelationKind::PartitionedTable => Self::PartitionedTable,
            RelationKind::View => Self::View,
            RelationKind::MaterializedView => Self::MaterializedView,
            RelationKind::ForeignTable => Self::ForeignTable,
            RelationKind::Sequence => Self::Sequence,
        }
    }
}

impl From<FunctionKind> for ObjectKind {
    fn from(k: FunctionKind) -> Self {
        match k {
            FunctionKind::Function => Self::Function,
            FunctionKind::Procedure => Self::Procedure,
            FunctionKind::Aggregate => Self::Aggregate,
            FunctionKind::Window => Self::Window,
        }
    }
}

